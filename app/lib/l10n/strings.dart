extension SContext on BuildContext {
  S get s => S.of(this);
}

class _SDelegate extends LocalizationsDelegate<S> {
  const _SDelegate();

  @override
  bool isSupported(Locale locale) => locale.languageCode == 'id' || locale.languageCode == 'en';

  @override
  Future<S> load(Locale locale) async => S.current = S.forLanguage(locale.languageCode);

  @override
  bool shouldReload(_SDelegate old) => false;
}
